def get_frequency_score(word):
    """
    计算词条的频率分数
    分数越小表示越常用（优先级越高）
    """
    word_len = len(word)

    # 单字处理
    if word_len == 1:
        if word in COMMON_CHARS_FREQ:
            return COMMON_CHARS_FREQ[word]
        else:
            # 未知单字，给予中等优先级
            return 10000 + hash(word) % 100000

    # 词组处理
    if word in COMMON_WORDS_FREQ:
        # 常用词组，基础分数 + 长度惩罚
        return 500 + COMMON_WORDS_FREQ[word] + (word_len - 2) * 100

    # 未知词组，根据长度和首字频率估算
    base_score = 20000

    # 首字如果是常用字，降低分数（提高优先级）
    if word[0] in COMMON_CHARS_FREQ:
        first_char_freq = COMMON_CHARS_FREQ[word[0]]
        base_score = 15000 + first_char_freq * 10

    # 长度惩罚：越长的词组优先级越低
    length_penalty = (word_len - 2) * 1000

    # 添加哈希值避免相同分数
    hash_offset = hash(word) % 1000

    return base_score + length_penalty + hash_offset

def reorder_pinyin_file(input_file, output_file):
    """
    重新排序 pinyin.txt 文件
    """
    print(f"正在读取文件: {input_file}")

    # 读取所有行
    entries = []
    with open(input_file, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue

            parts = line.split('\t')
            if len(parts) != 4:
                print(f"警告: 第 {line_num} 行格式不正确，跳过: {line}")
                continue

            word, pinyin, shortcut, hash_val = parts

            # 计算频率分数
            freq_score = get_frequency_score(word)

            entries.append({
                'word': word,
                'pinyin': pinyin,
                'shortcut': shortcut,
                'hash': hash_val,
                'freq_score': freq_score,
                'original_line': line_num
            })

            if line_num % 100000 == 0:
                print(f"已处理 {line_num} 行...")

    print(f"共读取 {len(entries)} 条词条")
    print("正在排序...")

    # 排序规则：
    # 1. 按频率分数排序（分数越小越靠前）
    # 2. 相同分数时，按词长排序（短词优先）
    # 3. 相同词长时，保持原有顺序
    entries.sort(key=lambda x: (x['freq_score'], len(x['word']), x['original_line']))

    print("正在写入新文件...")

    # 写入排序后的文件
    with open(output_file, 'w', encoding='utf-8') as f:
        for entry in entries:
            f.write(f"{entry['word']}\t{entry['pinyin']}\t{entry['shortcut']}\t{entry['hash']}\n")

    print(f"完成！新文件已保存到: {output_file}")

    # 显示前50个词条
    print("\n前50个词条预览：")
    for i, entry in enumerate(entries[:50], 1):
        print(f"{i:3d}. {entry['word']:8s} {entry['pinyin']:20s} (原行号: {entry['original_line']}, 分数: {entry['freq_score']})")

