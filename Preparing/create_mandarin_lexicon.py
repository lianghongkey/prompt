def create_pinyin_lexicon():
    """Create a complete Mandarin pinyin lexicon file."""
    pinyin_converter = Pinyin()
    single_chars, multi_chars = get_mandarin_lexicon()

    entries = []

    # Process single characters
    seen = set()
    for char in single_chars:
        if char in seen:
            continue
        pinyin = pinyin_converter.get_pinyin(char, splitter=' ')
        entries.append(f"{char}\t{pinyin}")
        seen.add(char)

    # Process multi-character words
    for word in multi_chars:
        if word in seen:
            continue
        pinyin = pinyin_converter.get_pinyin(word, splitter=' ')
        entries.append(f"{word}\t{pinyin}")
        seen.add(word)

    return entries

def main():
    print("Creating Mandarin Chinese (Simplified) pinyin lexicon...")
    entries = create_pinyin_lexicon()

    # Write to pinyin.txt
    pinyin_txt_path = "/Users/colin/develop/TypeDuck-Mac/Preparing/Sources/Preparing/Resources/pinyin.txt"
    with open(pinyin_txt_path, 'w', encoding='utf-8') as f:
        for entry in entries:
            f.write(entry + '\n')

    print(f"Created {len(entries)} entries in pinyin.txt")
    print(f"\nExample single-character entries:")
    for entry in entries[20:40]:
        print(f"  {entry}")
    print(f"\nExample multi-character entries:")
    # Show some multi-character entries
    multi_count = 0
    for entry in entries:
        if '\t' in entry:
            word = entry.split('\t')[0]
            if len(word) >= 2:
                print(f"  {entry}")
                multi_count += 1
                if multi_count >= 20:
                    break

if __name__ == "__main__":
    main()
